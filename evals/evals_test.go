var update = flag.Bool("update", false, "rewrite docs/evals/offline.md and offline.json")

// TestOfflineRun runs every scenario in both modes against its scripted model,
// with the real engine and tools, and checks the harness end to end: the
// graders pass, the metrics come out of the trace records, and the report is
// the checked-in docs/evals/offline report.
func TestOfflineRun(t *testing.T) {
	results, err := Run(context.Background(), Config{TurnTokens: 500000}, Scenarios(), Modes)
	if err != nil {
		t.Fatal(err)
	}
	if len(results) != 2*len(Scenarios()) {
		t.Fatalf("got %d results", len(results))
	}
	by := map[string]Result{}
	for _, r := range results {
		by[r.Scenario+"/"+string(r.Mode)] = r
		if !r.Success {
			t.Errorf("%s/%s failed: %s", r.Scenario, r.Mode, r.Why)
		}
		if r.ParentContextTokens == 0 || r.TotalTokens < r.ParentContextTokens || r.CostUSD <= 0 {
			t.Errorf("%s/%s: metrics missing: %+v", r.Scenario, r.Mode, r)
		}
		if r.Mode == Direct && r.Subtasks != 0 {
			t.Errorf("%s/direct started %d subtasks", r.Scenario, r.Subtasks)
		}
	}
	// What each scripted subtask run does, as the trace records report it.
	for name, want := range map[string]int{"code-search": 1, "research": 1, "chore": 1, "council": 4} {
		if got := by[name+"/subtask"].Subtasks; got != want {
			t.Errorf("%s/subtask: %d subtasks, want %d", name, got, want)
		}
		if got := by[name+"/subtask"].ParentToolCalls; got != 1 {
			t.Errorf("%s/subtask: %d parent tool calls, want 1", name, got)
		}
	}
	// Six writes ask for approval in both modes; a subtask's asks are relayed
	// to the root's gate.
	for _, m := range Modes {
		if got := by["chore/"+string(m)].Approvals; got != 6 {
			t.Errorf("chore/%s: %d approvals, want 6", m, got)
		}
	}
	// Delegating the reading keeps the tool output out of the parent.
	for _, name := range []string{"code-search", "research", "chore"} {
		if d, s := by[name+"/direct"], by[name+"/subtask"]; s.ParentContextTokens >= d.ParentContextTokens {
			t.Errorf("%s: subtask parent context %d not below direct %d", name, s.ParentContextTokens, d.ParentContextTokens)
		}
	}

	md := "# Code Mode evals: offline run\n\n" +
		"Generated by `go test ./evals -run TestOfflineRun -update`. The model is scripted and its\n" +
		"token counts are estimates from request size, so these numbers check the harness and compare how\n" +
		"much context each mode sends; they say nothing about model quality. Costs use the conservative\n" +
		"default price. See code-mode.md.\n\n" + Markdown(results, false)
	js, err := JSON(results, false)
	if err != nil {
		t.Fatal(err)
	}
	dir := filepath.Join("..", "docs", "evals")
	if *update {
		if err := os.MkdirAll(dir, 0o750); err != nil {
			t.Fatal(err)
		}
		for name, data := range map[string][]byte{"offline.md": []byte(md), "offline.json": js} {
			if err := os.WriteFile(filepath.Join(dir, name), data, 0o644); err != nil { //nolint:gosec // checked-in docs are world-readable
				t.Fatal(err)
			}
		}
	}
	for name, got := range map[string]string{"offline.md": md, "offline.json": string(js)} {
		want, err := os.ReadFile(filepath.Join(dir, name)) //nolint:gosec // fixed file names under docs/evals
		if err != nil {
			t.Fatalf("%v (run with -update to create it)", err)
		}
		if string(want) != got {
			t.Errorf("docs/evals/%s is out of date; run go test ./evals -run TestOfflineRun -update\n%s", name, got)
		}
	}
}

// TestDollarCapStopsTheRun: once the estimated spend reaches the cap, the run
// in progress ends and the rest are skipped.
func TestDollarCapStopsTheRun(t *testing.T) {
	results, err := Run(context.Background(), Config{MaxUSD: 0.01}, Scenarios(), Modes)
	if err != nil {
		t.Fatal(err)
	}
	skipped := 0
	for _, r := range results {
		if r.Skipped != "" {
			skipped++
		}
	}
	if skipped == 0 || skipped == len(results) {
		t.Fatalf("want some runs skipped by the cap, got %d of %d: %+v", skipped, len(results), results)
	}
}

func TestFind(t *testing.T) {
	if s, err := Find("council", "chore"); err != nil || len(s) != 2 || s[0].Name != "council" {
		t.Fatalf("Find = %v, %v", s, err)
	}
	if _, err := Find("nope"); err == nil {
		t.Fatal("unknown scenario found")
	}
}
