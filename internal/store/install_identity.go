package store

import (
	"context"
	"database/sql"
	"errors"
	"fmt"
	"strings"

	"github.com/google/uuid"
)

// ErrInstallHasEnrolledAgents is returned by RegenerateInstallID when any
// agent already has an actor binding or instance and force is not set.
var ErrInstallHasEnrolledAgents = errors.New("install has enrolled agents")

// InstallIdentity is the single install_identity row.
type InstallIdentity struct {
	InstallID         string `json:"install_id"`
	PreviousInstallID string `json:"previous_install_id,omitempty"`
	RegeneratedAt     string `json:"regenerated_at,omitempty"`
	CreatedAt         string `json:"created_at"`
}

// EnsureInstallID returns this install's id, minting a random UUID the first
// time. It is idempotent and safe under concurrent callers: the insert is
// INSERT OR IGNORE on the singleton key, then the stored value is read back,
// so every caller sees the one winner. The id is never derived from the
// hostname or any address.
func (s *Store) EnsureInstallID(ctx context.Context) (string, error) {
	if _, err := s.DB.ExecContext(ctx,
		`INSERT OR IGNORE INTO install_identity (id, install_id) VALUES (1, ?)`,
		uuid.NewString()); err != nil {
		return "", fmt.Errorf("mint install id: %w", err)
	}
	return s.InstallID(ctx)
}

// InstallID reads the stored install id without minting.
func (s *Store) InstallID(ctx context.Context) (string, error) {
	var id string
	err := s.DB.QueryRowContext(ctx, `SELECT install_id FROM install_identity WHERE id = 1`).Scan(&id)
	if err != nil {
		return "", fmt.Errorf("read install id: %w", err)
	}
	return id, nil
}

// GetInstallIdentity returns the full row for the operator CLI.
func (s *Store) GetInstallIdentity(ctx context.Context) (InstallIdentity, error) {
	if _, err := s.EnsureInstallID(ctx); err != nil {
		return InstallIdentity{}, err
	}
	var ii InstallIdentity
	err := s.DB.QueryRowContext(ctx,
		`SELECT install_id, previous_install_id, regenerated_at, created_at FROM install_identity WHERE id = 1`).
		Scan(&ii.InstallID, &ii.PreviousInstallID, &ii.RegeneratedAt, &ii.CreatedAt)
	if err != nil {
		return InstallIdentity{}, fmt.Errorf("read install identity: %w", err)
	}
	return ii, nil
}

// EnrolledAgentCount counts durable-actor rows that carry or depend on an
// enrollment: every agent_actor_bindings row (enabled or not) and every
// actor_instances row (including archived). Any nonzero count means an
// external key built from the current install id may already exist in Tether.
func (s *Store) EnrolledAgentCount(ctx context.Context) (int, error) {
	return enrolledAgentCount(ctx, s.DB)
}

type rowQuerier interface {
	QueryRowContext(context.Context, string, ...any) *sql.Row
}

func enrolledAgentCount(ctx context.Context, q rowQuerier) (int, error) {
	var n int
	err := q.QueryRowContext(ctx, `SELECT
		(SELECT COUNT(*) FROM agent_actor_bindings) +
		(SELECT COUNT(*) FROM actor_instances)`).Scan(&n)
	if err != nil {
		return 0, fmt.Errorf("count enrolled agents: %w", err)
	}
	return n, nil
}

// RegenerateInstallID replaces the install id with a fresh random UUID. It is
// meant for a database that was cloned or restored onto a second install,
// before any agent is enrolled from it. It refuses with
// ErrInstallHasEnrolledAgents when any binding or actor instance exists, unless
// force is set. Agents already enrolled keep their stored URN; the external key
// they were registered under in Tether is not rewritten, so forcing orphans the
// old key's link to this install. The change is recorded in event_log.
func (s *Store) RegenerateInstallID(ctx context.Context, force bool, actor string) (InstallIdentity, error) {
	if _, err := s.EnsureInstallID(ctx); err != nil {
		return InstallIdentity{}, err
	}
	tx, err := s.DB.BeginTx(ctx, nil)
	if err != nil {
		return InstallIdentity{}, fmt.Errorf("begin tx: %w", err)
	}
	defer rollbackUnlessCommitted(tx)

	n, err := enrolledAgentCount(ctx, tx)
	if err != nil {
		return InstallIdentity{}, err
	}
	if n > 0 && !force {
		return InstallIdentity{}, fmt.Errorf("%w: %d binding/instance row(s); pass force to regenerate anyway", ErrInstallHasEnrolledAgents, n)
	}
	var old string
	if err := tx.QueryRowContext(ctx, `SELECT install_id FROM install_identity WHERE id = 1`).Scan(&old); err != nil {
		return InstallIdentity{}, fmt.Errorf("read install id: %w", err)
	}
	fresh := uuid.NewString()
	if _, err := tx.ExecContext(ctx,
		`UPDATE install_identity SET install_id = ?, previous_install_id = ?,
		 regenerated_at = strftime('%Y-%m-%dT%H:%M:%fZ','now') WHERE id = 1`, fresh, old); err != nil {
		return InstallIdentity{}, fmt.Errorf("regenerate install id: %w", err)
	}
	detail := fmt.Sprintf("install id regenerated by %s (forced=%t, enrolled_rows=%d)", strings.TrimSpace(actor), force, n)
	meta := fmt.Sprintf(`{"previous_install_id":%q,"install_id":%q,"forced":%t,"enrolled_rows":%d}`, old, fresh, force, n)
	if _, err := tx.ExecContext(ctx,
		`INSERT INTO event_log (session_id, event_type, category, detail, metadata) VALUES ('', 'install_identity_regenerated', 'audit', ?, ?)`,
		detail, meta); err != nil {
		return InstallIdentity{}, fmt.Errorf("audit install id regeneration: %w", err)
	}
	if err := tx.Commit(); err != nil {
		return InstallIdentity{}, fmt.Errorf("commit: %w", err)
	}
	return s.GetInstallIdentity(ctx)
}

// TetherEnrollmentKey builds the Tether external key for an agent:
// nanite/<install_id>/<host_settings_id>. Both parts are required and must not
// contain "/" so the key parses unambiguously.
func TetherEnrollmentKey(installID, hostSettingsID string) (string, error) {
	for name, v := range map[string]string{"install id": installID, "host settings id": hostSettingsID} {
		if strings.TrimSpace(v) == "" || strings.ContainsAny(v, "/ \t\n") {
			return "", fmt.Errorf("enrollment key: invalid %s %q", name, v)
		}
	}
	return "nanite/" + installID + "/" + hostSettingsID, nil
}

// EnrollmentKey is TetherEnrollmentKey for this install's stored id.
func (s *Store) EnrollmentKey(ctx context.Context, hostSettingsID string) (string, error) {
	id, err := s.EnsureInstallID(ctx)
	if err != nil {
		return "", err
	}
	return TetherEnrollmentKey(id, hostSettingsID)
}
